#!/bin/sh
# Builds ~/.codex/AGENTS.md from jstack's general rules plus this machine's own.
# Claude Code reads the same file through `@~/.codex/AGENTS.md` in ~/.claude/CLAUDE.md.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
local_rules="${JSTACK_LOCAL_AGENTS:-$HOME/.config/jstack/AGENTS.local.md}"
out="$HOME/.codex/AGENTS.md"
marker="<!-- Generated by jstack global/install.sh. Edit global/AGENTS.md in jstack or $local_rules, then rerun. -->"

mkdir -p "$(dirname "$out")"

# A hand-written file is kept, never overwritten.
if [ -f "$out" ] && ! head -n 1 "$out" | grep -q 'Generated by jstack'; then
  backup="$out.before-jstack.$(date +%Y%m%d%H%M%S)"
  cp "$out" "$backup"
  echo "kept the hand-written file as $backup"
fi

tmp="$out.tmp.$$"
{
  echo "$marker"
  echo
  cat "$here/AGENTS.md"
  if [ -f "$local_rules" ]; then
    echo
    cat "$local_rules"
  fi
} > "$tmp"
mv "$tmp" "$out"
echo "wrote $out"
