#!/bin/sh
# Builds ~/.codex/AGENTS.md from, in order:
#   1. this repository's global/AGENTS.md (general rules, public);
#   2. <private>/personal.md (your rules for your own projects);
#   3. <private>/machines/<machine>.md (this machine's facts), if present.
# Claude Code reads the same file through `@~/.codex/AGENTS.md` in ~/.claude/CLAUDE.md.
#
# Usage: install.sh [--private <dir>] [--machine <name>]
#   --private  a clone of your private rules repository
#              (default: $JSTACK_PRIVATE, else a jstack-private clone next to this one)
#   --machine  the machines/ file to use (default: hostname -s)
set -eu

here=$(cd "$(dirname "$0")" && pwd)
private="${JSTACK_PRIVATE:-$here/../../jstack-private}"
machine=$(hostname -s)

while [ $# -gt 0 ]; do
  case "$1" in
    --private) private="$2"; shift 2 ;;
    --machine) machine="$2"; shift 2 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

out="$HOME/.codex/AGENTS.md"

parts="$here/AGENTS.md"
if [ -d "$private" ]; then
  private=$(cd "$private" && pwd)
  [ -f "$private/personal.md" ] && parts="$parts $private/personal.md"
  if [ -f "$private/machines/$machine.md" ]; then
    parts="$parts $private/machines/$machine.md"
  else
    echo "no machines/$machine.md in $private; skipping machine rules" >&2
  fi
else
  echo "no private rules at $private; using the general rules only" >&2
fi

mkdir -p "$(dirname "$out")"

# A hand-written file is kept, never overwritten.
if [ -f "$out" ] && ! head -n 1 "$out" | grep -q 'Generated by jstack'; then
  backup="$out.before-jstack.$(date +%Y%m%d%H%M%S)"
  cp "$out" "$backup"
  echo "kept the hand-written file as $backup"
fi

tmp="$out.tmp.$$"
{
  echo "<!-- Generated by jstack global/install.sh from: $parts. Edit those, then rerun. -->"
  for part in $parts; do
    echo
    cat "$part"
  done
} > "$tmp"
mv "$tmp" "$out"
echo "wrote $out from:"
for part in $parts; do echo "  $part"; done
